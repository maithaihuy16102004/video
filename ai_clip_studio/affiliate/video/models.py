@dataclass
class TrackSample:
    """One (time, box) observation of a tracked text region.

    Recorded by ``ocr.track_detections`` for every OCR sample that
    joined the track. Boxes are pixels in a frame of the region's
    ``frame_size`` — the same coordinate space as ``TextRegion.bbox``.
    The tracked-blur builder (``text_replace``) interpolates between
    samples so the blur box follows moving text across frames.
    Regions without samples (manual entry, single-sample tracks) fall
    back to the static median ``bbox``.
    """
    time: float
    bbox: BBox

    def to_dict(self) -> dict[str, Any]:
        return {"time": self.time, "bbox": self.bbox.to_dict()}

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "TrackSample":
        box = data["bbox"]
        return cls(time=float(data["time"]),
                   bbox=BBox(float(box["x"]), float(box["y"]),
                             float(box["w"]), float(box["h"])))


@dataclass
class TextRegion:
    """One tracked text region (one OCR track after temporal tracking).

    ``bbox``/``polygon`` are in pixels in a frame of ``frame_size``.
    ``removal_approved`` starts False and is set only by
    ``ocr.approve_removal`` — classification alone never approves
    anything.
    """
    text_id: str
    track_id: str
    original_text: str
    start_time: float
    end_time: float
    bbox: BBox
    frame_size: tuple[int, int]
    polygon: list[tuple[float, float]] = field(default_factory=list)
    ocr_confidence: float = 0.0
    classification: TextClassification = TextClassification.UNKNOWN
    classification_reason: str = ""
    source: str = "ocr"  # "ocr" | "manual" | "candidate"
    detection_method: str = ""
    translated_text: str = ""  # filled by Subagent B's translation stage
    needs_review: bool = False
    review_reasons: list[str] = field(default_factory=list)
    removal_approved: bool = False
    removal_approval: dict[str, Any] | None = None
    track_samples: list[TrackSample] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["bbox"] = self.bbox.to_dict()
        data["classification"] = self.classification.value
        return data

    def to_ocr_track_dict(self) -> dict[str, Any]:
        """Schema-shaped OcrTrack dict (normalized 0..1 box)."""
        fw, fh = self.frame_size
        polygon = [[px / fw, py / fh] for px, py in self.polygon]
        return {
            "text_id": self.text_id,
            "original_text": self.original_text,
            "translated_text": self.translated_text,
            "start_time": round(self.start_time, 3),
            "end_time": round(self.end_time, 3),
            "bounding_box": [round(v, 4) for v in
                             self.bbox.normalized(fw, fh)],
            "polygon": [[round(px, 4), round(py, 4)] for px, py in polygon],
            "track_id": self.track_id,
            "ocr_confidence": round(self.ocr_confidence, 4),
            "text_classification": self.classification.value,
        }


