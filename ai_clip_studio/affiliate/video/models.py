# Authorization (schema vocabulary + one test-only value)
# ---------------------------------------------------------------------

# B's schema vocabulary (AFFILIATE_PROJECT_V1). SYNTHETIC_FIXTURE is a
# Phase-1-only provenance label for assets generated by the test
# fixture generator; at the schema gate it maps to USER_OWNED because
# the fixture is content we generated ourselves. It must never appear
# in a real user project.
AUTHORIZATION_TYPES = ("USER_OWNED", "LICENSED", "SELLER_AUTHORIZED",
                       "UNKNOWN", "SYNTHETIC_FIXTURE")
SCHEMA_AUTHORIZATION_TYPES = ("USER_OWNED", "LICENSED",
                              "SELLER_AUTHORIZED", "UNKNOWN")


def export_gate_check(authorization_type: str,
                      commercial_rights_confirmed: bool) -> tuple[bool, list[str]]:
    """The export gate, engine-level mirror of schema.export_allowed.

    Returns (allowed, reasons). Export is REFUSED when the
    authorization is UNKNOWN, the commercial-rights confirmation is
    missing, or the authorization value is not recognized.
    """
    reasons: list[str] = []
    auth = (authorization_type or "").upper()
    if auth not in AUTHORIZATION_TYPES:
        reasons.append(f"unknown authorization type {authorization_type!r}")
    elif auth == "UNKNOWN":
        reasons.append("source authorization is UNKNOWN — export refused "
                       "until the user confirms the source is owned or "
                       "licensed for commercial reuse")
    if not commercial_rights_confirmed:
        reasons.append("commercial usage rights not confirmed")
    return (not reasons), reasons


def to_schema_authorization(authorization_type: str) -> str:
    """Map the engine authorization value to the schema vocabulary."""
    if authorization_type == "SYNTHETIC_FIXTURE":
        return "USER_OWNED"
    return authorization_type


