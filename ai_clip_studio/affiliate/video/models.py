@dataclass
class MaskSpec:
    """One user/edit mask over a text region.

    The mask-drawing UI is Subagent B's frontend work; this is the
    data model + the application input. ``mode`` selects how the
    masked area is treated. Masks never target watermarks or
    attribution unless the linked TextRegion has an approved removal.
    """
    mask_id: str
    shape: str  # "rect" | "rounded_rect" | "polygon"
    bbox: BBox | None
    polygon: list[tuple[float, float]] = field(default_factory=list)
    start_time: float = 0.0
    end_time: float = 0.0
    track_id: str = ""
    mode: str = "blur"  # "overlay" | "blur" | "inpaint"
    parameters: dict[str, Any] = field(default_factory=dict)
    approved: bool = False
    approval_note: str = ""
    purpose: str = ""

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["bbox"] = self.bbox.to_dict() if self.bbox else None
        return data

    def to_edit_operation_dict(self) -> dict[str, Any]:
        """Schema-shaped EditOperation (operation='manual_mask')."""
        params = dict(self.parameters)
        params.update({"shape": self.shape,
                       "bbox": self.bbox.to_dict() if self.bbox else None,
                       "polygon": [list(p) for p in self.polygon],
                       "mode": self.mode, "purpose": self.purpose})
        return {
            "operation": "manual_mask",
            "parameters": params,
            "start_time": self.start_time,
            "end_time": self.end_time,
            "target_track_id": self.track_id,
            "approved": self.approved,
            "approval_note": self.approval_note,
        }


