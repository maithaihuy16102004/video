@dataclass
class QACheck:
    name: str
    status: str  # "PASS" | "FAIL" | "PENDING"
    measured: Any
    threshold: str
    evidence: str
    method: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class QAReport:
    target_path: str
    profile_name: str
    checks: list[QACheck] = field(default_factory=list)
    measured_specs: dict[str, Any] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)

    @property
    def hard_fail_count(self) -> int:
        return sum(1 for c in self.checks if c.status == "FAIL")

    @property
    def status(self) -> str:
        if self.hard_fail_count:
            return "FAIL"
        if any(c.status == "PENDING" for c in self.checks):
            return "PENDING"
        return "PASS"

    def to_dict(self) -> dict[str, Any]:
        return {
            "target_path": self.target_path,
            "profile_name": self.profile_name,
            "status": self.status,
            "hard_fail_count": self.hard_fail_count,
            "checks": [c.to_dict() for c in self.checks],
            "measured_specs": self.measured_specs,
            "notes": self.notes,
        }
