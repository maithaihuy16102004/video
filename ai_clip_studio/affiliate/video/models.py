@dataclass
class SubtitleSlot:
    """Timing + region data for one Vietnamese subtitle overlay.

    Produced from an approved LOCAL_BLUR replacement: the blur pass
    removes the original on-screen text and the subtitle stage
    (Subagent B) renders the Vietnamese translation into this slot.
    The slot carries NO translated text — translation is B's scope —
    only the timing, region, and provenance B needs to place it.
    """
    slot_id: str
    text_id: str
    track_id: str
    start_time: float
    end_time: float
    bbox: BBox  # pixel coords in the source frame
    frame_size: tuple[int, int]
    classification: TextClassification
    original_text: str
    source: str = "blur_replacement"

    @property
    def normalized_bbox(self) -> list[float]:
        """[x, y, w, h] in 0..1, matching the schema OcrTrack box."""
        fw, fh = self.frame_size
        return [round(self.bbox.x / fw, 4), round(self.bbox.y / fh, 4),
                round(self.bbox.w / fw, 4), round(self.bbox.h / fh, 4)]

    def to_dict(self) -> dict[str, Any]:
        return {
            "slot_id": self.slot_id,
            "text_id": self.text_id,
            "track_id": self.track_id,
            "start_time": self.start_time,
            "end_time": self.end_time,
            "bbox": [self.bbox.x, self.bbox.y, self.bbox.w, self.bbox.h],
            "bbox_normalized": self.normalized_bbox,
            "frame_size": list(self.frame_size),
            "classification": self.classification.value,
            "original_text": self.original_text,
            "source": self.source,
            "handling": DEFAULT_TEXT_HANDLING,
        }


