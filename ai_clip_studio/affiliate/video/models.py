@dataclass
class BBox:
    """Pixel bounding box: top-left (x, y), size (w, h)."""
    x: float
    y: float
    w: float
    h: float

    @property
    def x2(self) -> float:
        return self.x + self.w

    @property
    def y2(self) -> float:
        return self.y + self.h

    @property
    def area(self) -> float:
        return max(0.0, self.w) * max(0.0, self.h)

    def iou(self, other: "BBox") -> float:
        ix = max(0.0, min(self.x2, other.x2) - max(self.x, other.x))
        iy = max(0.0, min(self.y2, other.y2) - max(self.y, other.y))
        inter = ix * iy
        union = self.area + other.area - inter
        return inter / union if union > 0 else 0.0

    def clamp(self, frame_w: int, frame_h: int) -> "BBox":
        x = min(max(0.0, self.x), max(0.0, frame_w - 1))
        y = min(max(0.0, self.y), max(0.0, frame_h - 1))
        w = min(max(0.0, self.w), frame_w - x)
        h = min(max(0.0, self.h), frame_h - y)
        return BBox(x, y, w, h)

    def expand(self, margin_px: float, frame_w: int, frame_h: int) -> "BBox":
        return BBox(self.x - margin_px, self.y - margin_px,
                    self.w + 2 * margin_px, self.h + 2 * margin_px).clamp(
                        frame_w, frame_h)

    def normalized(self, frame_w: int, frame_h: int) -> list[float]:
        return [self.x / frame_w, self.y / frame_h,
                self.w / frame_w, self.h / frame_h]

    @classmethod
    def from_normalized(cls, box: list[float], frame_w: int,
                        frame_h: int) -> "BBox":
        x, y, w, h = (float(v) for v in box)
        return cls(x * frame_w, y * frame_h, w * frame_w, h * frame_h)

    def to_xyxy(self) -> list[float]:
        return [self.x, self.y, self.x2, self.y2]

    def to_dict(self) -> dict[str, float]:
        return {"x": self.x, "y": self.y, "w": self.w, "h": self.h}


