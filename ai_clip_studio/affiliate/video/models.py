@dataclass
class AnalysisReport:
    source: SourceInfo
    scenes: list[SceneSegment] = field(default_factory=list)
    faces: list[FaceDetection] = field(default_factory=list)
    faces_status: str = "not_run"  # "ok" | "unavailable" | "not_run"
    faces_status_detail: str = ""
    hands_status: str = "unavailable"
    hands_status_detail: str = ("no hand-detection model installed; "
                                "MediaPipe/hand model required")
    watermark_candidates: list[WatermarkCandidate] = field(default_factory=list)
    text_candidates: list[TextRegion] = field(default_factory=list)
    audio_segments: list[AudioSegment] = field(default_factory=list)
    motion_summary: dict[str, Any] = field(default_factory=dict)
    engine: str = "ffmpeg+numpy"
    engine_detail: str = ""
    capability_notes: list[str] = field(default_factory=list)

    @property
    def faces_detected(self) -> bool:
        return len(self.faces) > 0

    def to_dict(self) -> dict[str, Any]:
        return {
            "source": self.source.to_dict(),
            "scenes": [s.to_dict() for s in self.scenes],
            "faces": [f.to_dict() for f in self.faces],
            "faces_status": self.faces_status,
            "faces_status_detail": self.faces_status_detail,
            "hands_status": self.hands_status,
            "hands_status_detail": self.hands_status_detail,
            "watermark_candidates": [w.to_dict()
                                     for w in self.watermark_candidates],
            "text_candidates": [t.to_dict() for t in self.text_candidates],
            "audio_segments": [a.to_dict() for a in self.audio_segments],
            "motion_summary": self.motion_summary,
            "engine": self.engine,
            "engine_detail": self.engine_detail,
            "capability_notes": self.capability_notes,
        }

    def to_video_analysis_dict(self) -> dict[str, Any]:
        """Schema-shaped VideoAnalysis dict (ASR fields stay empty: B)."""
        motion = self.motion_summary.get("label", "")
        return {
            "scenes": [s.to_analysis_scene_dict() for s in self.scenes],
            "faces_detected": self.faces_detected,
            "hands_detected": False,
            "motion_intensity": motion,
            "has_speech": False,  # set by Subagent B's ASR stage
            "silence_segments": [
                {"start_time": round(a.start_time, 3),
                 "end_time": round(a.end_time, 3)}
                for a in self.audio_segments if a.kind == "silence"],
            "engine": self.engine,
            "engine_detail": self.engine_detail,
        }


