"""Engine-level data models for the Affiliate Studio video side.

These dataclasses are the internal representation used by the CV /
editing engines. They convert to AFFILIATE_PROJECT_V1 schema-shaped
dicts (see ``ai_clip_studio/affiliate/schema.py``) through the
``to_*_dict`` helpers, so integration never has to guess field
meanings. Schema field vocabularies (orientation values, text
classes, operation names, QA statuses) are reused verbatim.

Design notes:
  * Pixel boxes are stored in pixels plus the frame size they belong
    to; schema boxes are normalized 0..1. Conversion is explicit.
  * Classification NEVER implies removability. ``removal_approved``
    on a TextRegion starts False and is set only through
    ``ocr.approve_removal`` with authorization + explicit approval.
  * No model here carries product facts, prices, or claims.
"""
