@dataclass
class SourceInfo:
    """Measured source-video metadata (ffprobe + SHA-256)."""
    path: str
    file_name: str
    file_size_bytes: int
    sha256: str
    width: int
    height: int
    fps: float
    duration_sec: float
    video_codec: str
    audio_codec: str
    pix_fmt: str
    bitrate: int
    container: str
    rotation_deg: float = 0.0  # display-matrix rotation, if present
    probe_raw: dict[str, Any] = field(default_factory=dict)

    @property
    def has_audio(self) -> bool:
        return bool(self.audio_codec)

    @property
    def orientation(self) -> str:
        """Schema vocabulary: vertical | horizontal | square."""
        w, h = self.width, self.height
        if self.rotation_deg in (90.0, 270.0):
            w, h = h, w
        if w == h:
            return "square"
        return "vertical" if h > w else "horizontal"

    @property
    def aspect_ratio(self) -> str:
        """Reduced W:H string, e.g. '16:9' (rotation-aware)."""
        w, h = self.width, self.height
        if self.rotation_deg in (90.0, 270.0):
            w, h = h, w
        g = math.gcd(w, h) or 1
        return f"{w // g}:{h // g}"

    @property
    def resolution(self) -> str:
        return f"{self.width}x{self.height}"

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["has_audio"] = self.has_audio
        data["orientation"] = self.orientation
        data["aspect_ratio"] = self.aspect_ratio
        data["resolution"] = self.resolution
        return data

    def to_source_video_dict(self, stored_path: str = "") -> dict[str, Any]:
        """Schema-shaped SourceVideo dict."""
        return {
            "file_name": self.file_name,
            "file_size_bytes": self.file_size_bytes,
            "resolution": self.resolution,
            "fps": self.fps,
            "duration_sec": round(self.duration_sec, 3),
            "video_codec": self.video_codec,
            "audio_codec": self.audio_codec,
            "aspect_ratio": self.aspect_ratio,
            "orientation": self.orientation,
            "has_audio": self.has_audio,
            "container": self.container,
            "sha256": self.sha256,
            "stored_path": stored_path,
        }


